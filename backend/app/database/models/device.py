"""
Device database model representing authorized client installations across platforms.
"""

from datetime import datetime
from typing import TYPE_CHECKING, List, Optional
from sqlalchemy import Boolean, DateTime, ForeignKey, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from backend.app.database.base import Base, TimestampMixin
from backend.app.database.models.user import generate_uuid

if TYPE_CHECKING:
    from backend.app.database.models.session import RefreshTokenSession
    from backend.app.database.models.user import User


class Device(Base, TimestampMixin):
    """
    Represents an authorized hardware or client device (Windows, macOS, Linux, Android, iOS, Web).
    Identified by a persistent cryptographic or installation identifier generated by the client.
    """
    __tablename__ = "devices"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=generate_uuid,
        doc="Internal device record UUID"
    )
    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        doc="Owner user ID"
    )
    device_identifier: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        index=True,
        doc="Persistent unique installation or hardware identifier generated by client"
    )
    device_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        doc="Human-readable device label (e.g. Moneshwar's MacBook Pro)"
    )
    device_type: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        doc="Platform category: windows, macos, linux, android, ios, web, other"
    )
    client_version: Mapped[Optional[str]] = mapped_column(
        String(50),
        nullable=True,
        doc="Application build version of the client"
    )
    is_trusted: Mapped[bool] = mapped_column(
        Boolean,
        default=True,
        nullable=False,
        doc="Whether this device is pre-authorized for privileged assistant interactions"
    )
    is_revoked: Mapped[bool] = mapped_column(
        Boolean,
        default=False,
        nullable=False,
        doc="Whether access for this device has been revoked by the user"
    )
    revoked_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        doc="Timestamp of revocation"
    )
    last_ip_address: Mapped[Optional[str]] = mapped_column(
        String(45),
        nullable=True,
        doc="Last observed client IP address (IPv4/IPv6)"
    )
    last_seen_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        doc="Timestamp of last API interaction from this device"
    )

    # Relationships
    user: Mapped["User"] = relationship(back_populates="devices")
    sessions: Mapped[List["RefreshTokenSession"]] = relationship(
        back_populates="device",
        cascade="all, delete-orphan",
        order_by="desc(RefreshTokenSession.created_at)"
    )

    def __repr__(self) -> str:
        return f"<Device(id={self.id!r}, name={self.device_name!r}, type={self.device_type!r}, revoked={self.is_revoked!r})>"
