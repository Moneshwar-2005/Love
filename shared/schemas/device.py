"""
Pydantic schemas for multi-platform device registration, authorization, and management.
"""

from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field

from shared.constants import DeviceType


class DeviceRegisterRequest(BaseModel):
    """Payload to register or update an authorized client device."""
    device_identifier: str = Field(
        ...,
        min_length=8,
        max_length=128,
        description="Persistent installation or hardware UUID generated by client"
    )
    device_name: str = Field(
        ...,
        min_length=1,
        max_length=100,
        description="User-friendly device name (e.g. Moneshwar's MacBook Pro)"
    )
    device_type: DeviceType = Field(
        ...,
        description="Operating system/client category: windows, macos, linux, android, ios, web, other"
    )
    client_version: Optional[str] = Field(
        None,
        max_length=50,
        description="Client application version"
    )


class DeviceResponse(BaseModel):
    """Details of a registered client device."""
    id: str
    device_identifier: str
    device_name: str
    device_type: str
    client_version: Optional[str] = None
    is_trusted: bool
    is_revoked: bool
    revoked_at: Optional[datetime] = None
    last_seen_at: Optional[datetime] = None
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class DeviceListResponse(BaseModel):
    """List of registered devices for the user."""
    devices: List[DeviceResponse]
    total: int
